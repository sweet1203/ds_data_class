function psDraw(){
  $('psRows').innerHTML=PS_CASES.map((row,i)=>`<tr><td>${row[0]}</td><td><select aria-label="상황 ${i+1} 점검 결과" data-case="${i}"><option value="">선택하세요</option>${PS_OPTIONS.map((o,j)=>`<option value="${j}">${o}</option>`).join('')}</select></td><td class="ps-reason">확인 전</td></tr>`).join('');
  $('psFeedback').textContent='상황을 읽고 선택해 보세요.';
}
$('psCheck').onclick=()=>{
  let right=0;
  $('psRows').querySelectorAll('tr').forEach((tr,i)=>{
    const pick=tr.querySelector('select').value;
    const ok=pick!==''&&Number(pick)===PS_CASES[i][1];
    if(ok)right++;
    tr.querySelector('.ps-reason').textContent=(ok?'맞아요. ':pick===''?'아직 선택하지 않았어요. ':'다시 살펴봐요. ')+PS_CASES[i][2];
  });
  $('psFeedback').textContent=`${PS_CASES.length}개 중 ${right}개를 맞혔어요. 설명을 읽고 판단을 바꿔도 좋아요.`;
};
$('psReset').onclick=psDraw;
psDraw();
